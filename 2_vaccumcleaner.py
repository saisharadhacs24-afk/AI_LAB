def run_vacuum_agent(start_location, status_a, status_b):
    # 1 = Dirty, 0 = Clean
    environment = {'A': status_a, 'B': status_b}
    location = start_location
    cost = 0

    print(f"Initial State: Agent in Room {location} | Room A: {environment['A']} | Room B: {environment['B']}")

    while environment['A'] == 1 or environment['B'] == 1:
        # Percept: (current location, status of current room)
        current_status = environment[location]

        # Reflex Decision Logic
        if current_status == 1:
            print(f"Location {location} is DIRTY. Action: SUCK")
            environment[location] = 0  # Clean the room
            cost += 1
        elif location == 'A':
            print("Location A is CLEAN. Action: Move RIGHT to B")
            location = 'B'
            cost += 1
        elif location == 'B':
            print("Location B is CLEAN. Action: Move LEFT to A")
            location = 'A'
            cost += 1

    print(f"\nGoal Reached! Both rooms clean. Total Actions/Cost: {cost}")
    print(f"Final State: Room A: {environment['A']} | Room B: {environment['B']}")

# Test starting at State 1 (Agent in A, both dirty)
run_vacuum_agent(start_location='A', status_a=1, status_b=1)