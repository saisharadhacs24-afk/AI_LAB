#FORWARD CHAINING


# Initial facts
facts = {
    "American(Robert)",
    "Missile(T1)",
    "Owns(A,T1)",
    "Enemy(A,America)"
}

# Forward chaining
while True:
    old_count = len(facts)

    # Rule 1: Missiles are weapons
    if "Missile(T1)" in facts:
        facts.add("Weapon(T1)")

    # Rule 2: Enemy of America is hostile
    if "Enemy(A,America)" in facts:
        facts.add("Hostile(A)")

    # Rule 3: Robert sold missiles to country A
    if "Missile(T1)" in facts and "Owns(A,T1)" in facts:
        facts.add("Sells(Robert,T1,A)")

    # Rule 4: If all conditions are satisfied,
    # Robert is a criminal
    if ("American(Robert)" in facts and
        "Weapon(T1)" in facts and
        "Sells(Robert,T1,A)" in facts and
        "Hostile(A)" in facts):

        facts.add("Criminal(Robert)")

    # Stop when no new facts are added
    if len(facts) == old_count:
        break

# Display result
print("Derived Facts:")
for fact in sorted(facts):
    print(fact)

if "Criminal(Robert)" in facts:
    print("\nRobert is a Criminal: TRUE")
else:
    print("\nRobert is a Criminal: FALSE")

