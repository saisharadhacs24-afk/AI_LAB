#UNIFICATION

def unify(a, b):
    subst = {}

    for x, y in zip(a[1], b[1]):

        if x == y:
            continue

        elif x.islower():
            subst[x] = y

        elif y.islower():
            subst[y] = x

        else:
            return "FAILURE"

    return subst


# Given expressions
exp1 = ("Eats", ["x", "Apple"])
exp2 = ("Eats", ["Riya", "y"])

# Check predicate names and arguments
if exp1[0] != exp2[0] or len(exp1[1]) != len(exp2[1]):
    print("Unification Failed")
else:
    result = unify(exp1, exp2)
    print("Substitution Set:", result)

    if result != "FAILURE":
        print("Unification Successful")