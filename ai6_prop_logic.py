from itertools import product

def entails(kb, query):
    for P, Q, R in product([False, True], repeat=3):
        KB = ((not Q or P) and
              (not P or not Q) and
              (Q or R))

        if KB and not query(P, Q, R):
            return False
    return True

def query_R(P, Q, R):
    return R

def query_R_implies_P(P, Q, R):
    return not R or P

def query_Q_implies_R(P, Q, R):
    return not Q or R

print("KB entails R:", entails(None, query_R))
print("KB entails R -> P:",
      entails(None, query_R_implies_P))
print("KB entails Q -> R:",
      entails(None, query_Q_implies_R))