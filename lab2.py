# 1. Problem Configuration
INITIAL_STATE = ((1, 2, 3), (0, 4, 6), (7, 5, 8))
GOAL_STATE = ((1, 2, 3), (4, 5, 6), (7, 8, 0))
MOVES = [(-1, 0, 'UP'), (1, 0, 'DOWN'), (0, -1, 'LEFT'), (0, 1, 'RIGHT')]

def get_neighbors(state):
    # Find position of blank space (0)
    for r in range(3):
        for c in range(3):
            if state[r][c] == 0:
                zr, zc = r, c

    neighbors = []
    for dr, dc, move in MOVES:
        nr, nc = zr + dr, zc + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            grid = [list(row) for row in state]
            grid[zr][zc], grid[nr][nc] = grid[nr][nc], grid[zr][zc]
            neighbors.append((tuple(tuple(r) for r in grid), move))
    return neighbors

def solve_dfs(initial_state, max_depth=15):
    stack = [(initial_state, [])]
    visited = set()

    while stack:
        state, path = stack.pop()

        if state == GOAL_STATE:
            return path

        # Depth limit check to prevent infinite stack overflow in DFS
        if len(path) >= max_depth:
            continue

        visited.add(state)

        for neighbor, move in get_neighbors(state):
            if neighbor not in visited:
                stack.append((neighbor, path + [move]))

    return None

# Execution
path = solve_dfs(INITIAL_STATE)
print("=== DFS Solution ===")
print("Steps:", path)
print("Total Moves:", len(path) if path else "No Solution")

# 1. Problem Configuration
INITIAL_STATE = ((1, 2, 3), (0, 4, 6), (7, 5, 8))
GOAL_STATE = ((1, 2, 3), (4, 5, 6), (7, 8, 0))
MOVES = [(-1, 0, 'UP'), (1, 0, 'DOWN'), (0, -1, 'LEFT'), (0, 1, 'RIGHT')]

def get_neighbors(state):
    for r in range(3):
        for c in range(3):
            if state[r][c] == 0:
                zr, zc = r, c

    neighbors = []
    for dr, dc, move in MOVES:
        nr, nc = zr + dr, zc + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            grid = [list(row) for row in state]
            grid[zr][zc], grid[nr][nc] = grid[nr][nc], grid[zr][zc]
            neighbors.append((tuple(tuple(r) for r in grid), move))
    return neighbors

def dls(state, limit, path, visited):
    if state == GOAL_STATE:
        return path
    if len(path) == limit:
        return None

    visited.add(state)

    for neighbor, move in get_neighbors(state):
        if neighbor not in visited:
            result = dls(neighbor, limit, path + [move], visited)
            if result is not None:
                return result

    visited.remove(state)  # Backtrack
    return None

def solve_ids(initial_state, max_limit=10):
    for limit in range(max_limit + 1):
        visited = set()
        result = dls(initial_state, limit, [], visited)
        if result is not None:
            return result, limit
    return None, max_limit

# Execution
path, depth = solve_ids(INITIAL_STATE)
print("=== IDS Solution ===")
print(f"Goal Found at Depth Limit: {depth}")
print("Steps:", path)
print("Total Moves:", len(path) if path else "No Solution")