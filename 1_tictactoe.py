import math

# Board Layout Indices:
# 0 | 1 | 2
# ---------
# 3 | 4 | 5
# ---------
# 6 | 7 | 8

HUMAN = 'O'
AI = 'X'
EMPTY = ' '

WINNING_COMBINATIONS = [
    [0, 1, 2], [3, 4, 5], [6, 7, 8],  # Rows
    [0, 3, 6], [1, 4, 7], [2, 5, 8],  # Columns
    [0, 4, 8], [2, 4, 6]               # Diagonals
]

def print_board(board):
    print("\n")
    for i in range(3):
        row = [board[i * 3 + j] for j in range(3)]
        print(f" {row[0]} | {row[1]} | {row[2]} ")
        if i < 2:
            print("-----------")
    print("\n")

def check_winner(board):
    """Returns 'X' if AI wins, 'O' if Human wins, or None."""
    for combo in WINNING_COMBINATIONS:
        if board[combo[0]] == board[combo[1]] == board[combo[2]] != EMPTY:
            return board[combo[0]]
    return None

def is_board_full(board):
    return EMPTY not in board

def minimax(board, depth, is_maximizing):
    """Recursive Minimax algorithm evaluating terminal states and scores."""
    winner = check_winner(board)

    # Base Cases (Terminal Nodes in Game Tree)
    if winner == AI:
        return 10 - depth  # Prefer faster wins
    if winner == HUMAN:
        return depth - 10  # Prefer slower losses
    if is_board_full(board):
        return 0

    if is_maximizing:
        best_score = -math.inf
        for i in range(9):
            if board[i] == EMPTY:
                board[i] = AI                      # Make move
                score = minimax(board, depth + 1, False) # Recurse down tree
                board[i] = EMPTY                   # Backtrack (undo move)
                best_score = max(best_score, score)
        return best_score
    else:
        best_score = math.inf
        for i in range(9):
            if board[i] == EMPTY:
                board[i] = HUMAN                   # Make move
                score = minimax(board, depth + 1, True)  # Recurse down tree
                board[i] = EMPTY                   # Backtrack (undo move)
                best_score = min(best_score, score)
        return best_score

def get_best_move(board):
    """Finds the optimal move for the AI using Minimax."""
    best_score = -math.inf
    best_move = None

    for i in range(9):
        if board[i] == EMPTY:
            board[i] = AI
            score = minimax(board, 0, False)
            board[i] = EMPTY
            if score > best_score:
                best_score = score
                best_move = i

    return best_move

def play_game():
    board = [EMPTY] * 9
    print("Welcome to Tic-Tac-Toe!")
    print("Cell positions are 0-8 from top-left to bottom-right:")
    print(" 0 | 1 | 2 ")
    print("-----------")
    print(" 3 | 4 | 5 ")
    print("-----------")
    print(" 6 | 7 | 8 ")

    human_turn = True  # Human starts first ('O')

    while True:
        print_board(board)

        winner = check_winner(board)
        if winner:
            if winner == HUMAN:
                print("Congratulations! You won!")
            else:
                print("AI wins! Better luck next time.")
            break
        if is_board_full(board):
            print("It's a draw!")
            break

        if human_turn:
            try:
                move = int(input("Enter your move (0-8): "))
                if move < 0 or move > 8 or board[move] != EMPTY:
                    print("Invalid move. Spot is either taken or out of range.")
                    continue
                board[move] = HUMAN
                human_turn = False
            except ValueError:
                print("Please enter a valid integer between 0 and 8.")
        else:
            print("AI is calculating the best move...")
            move = get_best_move(board)
            board[move] = AI
            human_turn = True

if __name__ == "__main__":
    play_game()